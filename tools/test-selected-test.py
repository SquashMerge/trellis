    import unittest
    from pathlib import Path

    def ran(name):
        Path(os.environ["RAN"], name).touch()

    class Sample(unittest.TestCase):
        def test_passes(self):
            ran("python-passes")

        def test_passes_too(self):
            ran("python-passes-too")

        def test_fails(self):
            ran("python-fails")
