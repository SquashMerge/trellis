"""Checks of tools/test-selected on a small synthetic checkout (#1145).

The script finds its checkout from its own path, so each test copies it into a
temporary tree and runs it there, argv-style and from another directory. The
mapping tests read the printed commands; the end-to-end tests run real Node,
Python and (where cargo-nextest is installed) Cargo tests of that tree.
"""
