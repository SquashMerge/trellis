class Checkout(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        # Resolved: the script reports paths under its own physical root.
        self.outside = Path(temporary.name).resolve()
        self.root = self.outside / "checkout"
        self.ran = self.outside / "ran"
        self.ran.mkdir()
        for name, text in FILES.items():
            path = self.root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(textwrap.dedent(text))
        shutil.copy(SCRIPT, self.root / "tools/test-selected")

    def run_selected(self, *selectors, print_only=False, env=None):
        """Run the copied script the way a tool does: argv, no shell, another directory."""
        environ = {**os.environ, "RAN": str(self.ran), **(env or {})}
        environ.pop("TRELLIS_TEST_SELECTED_PRINT", None)
        environ.pop("CARGO_TARGET_DIR", None)
        if print_only:
            environ["TRELLIS_TEST_SELECTED_PRINT"] = "1"
        return subprocess.run(
            [str(self.root / "tools/test-selected"), *selectors],
            cwd=self.outside, env=environ, capture_output=True, text=True)

    def mapped(self, *selectors):
        result = self.run_selected(*selectors, print_only=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(sorted(os.listdir(self.ran)), [], "print mode ran a test")
        return result.stdout.splitlines()

    def cargo(self, arguments):
        return f"CARGO_TARGET_DIR={self.root}/target-test-support {NEXTEST} {arguments}"

    def assert_refused(self, selector, reason):
        # A selector that would run comes first: a refusal must stop it too.
        result = self.run_selected("tools/sample-test.py::test_passes", selector)
        self.assertEqual(result.returncode, 2, result.stdout + result.stderr)
        self.assertIn(f"refused {selector!r}: ", result.stderr)
        self.assertIn(reason, result.stderr)
        self.assertIn("nothing was run", result.stderr)
        self.assertEqual(result.stdout, "")
        self.assertEqual(sorted(os.listdir(self.ran)), [])


class Mapping(Checkout):
    def test_the_script_is_executable_and_names_its_interpreter(self):
        self.assertTrue(SCRIPT.stat().st_mode & stat.S_IXUSR)
        self.assertEqual(SCRIPT.read_text().splitlines()[0], "#!/usr/bin/env python3")

    def test_a_test_binary_file_runs_that_binary(self):
        self.assertEqual(self.mapped("tests/single.rs"), [self.cargo("--test single")])
        self.assertEqual(self.mapped("tests/suite/main.rs"), [self.cargo("--test suite")])

    def test_a_module_of_a_directory_test_binary_runs_that_module(self):
        self.assertEqual(self.mapped("tests/suite/cases.rs"),
                         [self.cargo("--test suite -E 'test(/^cases::/)'")])

    def test_a_path_attribute_decides_the_module(self):
        self.assertEqual(self.mapped("tests/suite/borrowed.rs"),
                         [self.cargo("--test suite -E 'test(/^outer::inner::/)'")])
        self.assertEqual(self.mapped("src/alpha_tests.rs"),
                         [self.cargo("--lib -E 'test(/^alpha::tests::/)'")])

    def test_a_library_file_runs_its_module(self):
        self.assertEqual(self.mapped("src/alpha.rs"), [self.cargo("--lib -E 'test(/^alpha::/)'")])
        self.assertEqual(self.mapped("src/alpha/beta.rs"), [self.cargo("--lib -E 'test(/^alpha::beta::/)'")])
        self.assertEqual(self.mapped("src/gamma/mod.rs"), [self.cargo("--lib -E 'test(/^gamma::/)'")])
        self.assertEqual(self.mapped("src/gamma/delta.rs"), [self.cargo("--lib -E 'test(/^gamma::delta::/)'")])
        self.assertEqual(self.mapped("src/nested/inner.rs"),
                         [self.cargo("--lib -E 'test(/^nested::inner::/)'")])
        self.assertEqual(self.mapped("src/lib.rs"), [self.cargo("--lib")])

    def test_a_binary_file_runs_that_binary(self):
        self.assertEqual(self.mapped("src/main.rs"), [self.cargo("--bin demo")])
        self.assertEqual(self.mapped("src/cli.rs"), [self.cargo("--bin demo -E 'test(/^cli::/)'")])
        self.assertEqual(self.mapped("src/bin/tool.rs"), [self.cargo("--bin tool")])

    def test_a_rust_test_name_is_matched_whole_inside_the_file_module(self):
        self.assertEqual(self.mapped("src/alpha.rs::tests::passes"),
                         [self.cargo("--lib -E 'test(/^alpha::(.+::)?tests::passes$/)'")])
        self.assertEqual(self.mapped("tests/single.rs::passes"),
                         [self.cargo("--test single -E 'test(/^(.+::)?passes$/)'")])

    def test_the_target_directory_follows_the_tests_lane(self):
        result = self.run_selected("tests/single.rs", print_only=True, env={})
        self.assertIn(f"CARGO_TARGET_DIR={self.root}/target-test-support ", result.stdout)
        environ = {**os.environ, "TRELLIS_TEST_SELECTED_PRINT": "1", "CARGO_TARGET_DIR": "/elsewhere/cache"}
        result = subprocess.run([str(self.root / "tools/test-selected"), "tests/single.rs"],
                                env=environ, capture_output=True, text=True)
        self.assertIn("CARGO_TARGET_DIR=/elsewhere/cache-test-support ", result.stdout)

    def test_node_tests_run_under_node_test(self):
        self.assertEqual(self.mapped("tests/unit.test.cjs"), ["node --test tests/unit.test.cjs"])
        self.assertEqual(self.mapped("tests/esm.test.mjs"), ["node --test tests/esm.test.mjs"])
        self.assertEqual(self.mapped("tools/semantic-contract/test/load.test.mjs"),
                         ["node --test tools/semantic-contract/test/load.test.mjs"])
        self.assertEqual(self.mapped("tools/synthetic-cohorts/test/cohorts.test.mjs"),
                         ["node --test tools/synthetic-cohorts/test/cohorts.test.mjs"])

    def test_the_herdr_mod_tests_load_their_hooks(self):
        self.assertEqual(self.mapped("herdr-mod/test/mod.test.mjs"),
                         ["node --import ./herdr-mod/test/register.mjs --test herdr-mod/test/mod.test.mjs"])

    def test_a_node_test_name_is_an_escaped_whole_name_pattern(self):
        self.assertEqual(self.mapped("tests/unit.test.cjs::passes (a.b)"),
                         [r"node --test '--test-name-pattern=^passes \(a\.b\)$' tests/unit.test.cjs"])

    def test_python_script_tests_run_themselves(self):
        self.assertEqual(self.mapped("tools/sample-test.py"), ["python3 tools/sample-test.py"])
        self.assertEqual(self.mapped("tools/sample-test.py::Sample.test_passes"),
                         ["python3 tools/sample-test.py -k '*.Sample.test_passes'"])

    def test_python_unittest_files_run_under_discover(self):
        discover = "python3 -m unittest discover -s tools/semantic-contract/test -p test_batch.py"
        self.assertEqual(self.mapped("tools/semantic-contract/test/test_batch.py"), [discover])
        self.assertEqual(self.mapped("tools/semantic-contract/test/test_batch.py::test_passes"),
                         [discover + " -k '*.test_passes'"])

    def test_a_node_test_that_needs_installed_packages_maps_once_they_are_there(self):
        self.assert_refused("tests/mcp-smoke.test.mjs", "tests/mcp packages, which are not installed")
        (self.root / "tests/mcp/node_modules").mkdir(parents=True)
        self.assertEqual(self.mapped("tests/mcp-smoke.test.mjs"), ["node --test tests/mcp-smoke.test.mjs"])

    def test_the_same_command_is_listed_once_and_order_is_kept(self):
        self.assertEqual(
            self.mapped("tools/sample-test.py", "tests/unit.test.cjs", "tools/sample-test.py",
                        "tools/../tools/sample-test.py"),
            ["python3 tools/sample-test.py", "node --test tests/unit.test.cjs"])

    def test_a_link_inside_the_checkout_maps_as_its_target(self):
        (self.root / "tests/link.test.cjs").symlink_to("unit.test.cjs")
        self.assertEqual(self.mapped("tests/link.test.cjs"), ["node --test tests/unit.test.cjs"])

    def test_this_repository_test_binaries_map_file_by_file(self):
        """The real sources parse: every file of a directory test binary maps to that binary."""
        files = sorted(
            str(path.relative_to(REPOSITORY))
            for main in REPOSITORY.glob("tests/*/main.rs") for path in main.parent.glob("*.rs"))
        if not files:
            self.skipTest("no directory test binaries here")
        result = subprocess.run([str(SCRIPT), *files], capture_output=True, text=True,
                                env={**os.environ, "TRELLIS_TEST_SELECTED_PRINT": "1"})
        self.assertEqual(result.returncode, 0, result.stderr)
        for file, line in zip(files, result.stdout.splitlines(), strict=True):
            self.assertIn(f" --test {file.split('/')[1]}", line + " ")


class Refusals(Checkout):
    def test_no_selector_is_a_usage_error(self):
        result = self.run_selected()
        self.assertEqual(result.returncode, 2)
        self.assertIn("usage:", result.stderr)

    def test_a_leading_dash_is_never_an_option(self):
        for selector in ("-k", "--print", "--help", "--", "-tests/unit.test.cjs"):
            self.assert_refused(selector, "must not start with `-`")

    def test_an_absolute_path(self):
        self.assert_refused(str(self.root / "tests/unit.test.cjs"), "relative to the repository root")

    def test_a_missing_path(self):
        self.assert_refused("tests/missing.test.cjs", "does not exist")
        self.assert_refused("", "the path is empty")
        (self.root / "tests/dangling.test.cjs").symlink_to("nowhere.cjs")
        self.assert_refused("tests/dangling.test.cjs", "broken symbolic link")

    def test_a_path_outside_the_checkout(self):
        (self.outside / "outside.test.cjs").write_text("")
        self.assert_refused("../outside.test.cjs", "outside the checkout")
        self.assert_refused("tests/../../outside.test.cjs", "outside the checkout")

    def test_a_link_that_leaves_the_checkout(self):
        (self.outside / "outside.test.cjs").write_text("")
        (self.root / "tests/escape.test.cjs").symlink_to(self.outside / "outside.test.cjs")
        self.assert_refused("tests/escape.test.cjs", "outside the checkout")
        (self.root / "tests/away").symlink_to(self.outside, target_is_directory=True)
        self.assert_refused("tests/away/outside.test.cjs", "outside the checkout")

    def test_a_directory(self):
        self.assert_refused("tests/suite", "not a file")
        self.assert_refused(".", "not a file")

    def test_an_unknown_layout(self):
        for selector in ("tests/notes.md", "tools/sample.py", "web/app.js", "Cargo.toml",
                         "tools/test-selected"):
            self.assert_refused(selector, "no test command is known for this layout")

    def test_layouts_another_lane_or_harness_owns(self):
        self.assert_refused("tests/browser/page.test.cjs", "./tools/verify --lane browser")
        self.assert_refused("tests/fixtures/data.test.cjs", "test data has no single test")
        self.assert_refused("tools/selection/shared.test.mjs", "no verify lane runs it")
        self.assert_refused("tools/extraction/extract.test.mjs", "no verify lane runs it")

    def test_a_rust_file_no_target_reaches(self):
        self.assert_refused("src/ghost.rs", "no Cargo library, binary or test target reaches this file")

    def test_a_rust_file_two_test_binaries_share(self):
        self.assert_refused("tests/support/helper.rs",
                            "2 targets share this file (test binary other, test binary suite)")

    def test_a_malformed_test_name(self):
        self.assert_refused("tests/unit.test.cjs::", "must be followed by a test name")
        self.assert_refused("tests/single.rs::not a name", "identifiers joined by `::`")
        self.assert_refused("tests/single.rs::/)|test(/", "identifiers joined by `::`")
        self.assert_refused("tools/sample-test.py::*", "`test_method` or `Class.test_method`")

    def test_a_test_name_the_file_does_not_hold(self):
        # node --test, and unittest before Python 3.12, pass when a name matches nothing.
        self.assert_refused("tests/unit.test.cjs::passes (a.c)", "does not contain that test name")
        self.assert_refused("tools/sample-test.py::test_missing", "does not define that test")
        self.assert_refused("tools/sample-test.py::Other.test_passes", "does not define that test")

    def test_every_refusal_is_reported(self):
        result = self.run_selected("-x", "tests/unit.test.cjs", "tests/missing.rs")
        self.assertEqual(result.returncode, 2)
        self.assertIn("refused '-x'", result.stderr)
        self.assertIn("refused 'tests/missing.rs'", result.stderr)
        self.assertEqual(sorted(os.listdir(self.ran)), [])


class Runs(Checkout):
    def test_a_python_script_test_runs_whole_and_fails_with_its_failure(self):
        result = self.run_selected("tools/sample-test.py")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("==> python3 tools/sample-test.py\n", result.stdout)
        self.assertEqual(sorted(os.listdir(self.ran)), ["python-fails", "python-passes", "python-passes-too"])

    def test_a_python_test_name_runs_only_that_test(self):
        result = self.run_selected("tools/sample-test.py::test_passes")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(sorted(os.listdir(self.ran)), ["python-passes"])

    def test_a_python_unittest_file_runs_under_discover(self):
        result = self.run_selected("tools/semantic-contract/test/test_batch.py::Sample.test_passes_too")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(sorted(os.listdir(self.ran)), ["python-passes-too"])

    def test_a_node_test_file_runs_whole_and_fails_with_its_failure(self):
        result = self.run_selected("tests/unit.test.cjs")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("==> node --test tests/unit.test.cjs\n", result.stdout)
        self.assertEqual(sorted(os.listdir(self.ran)), ["node-fails", "node-passes", "node-passes-again"])

    def test_a_node_test_name_runs_only_that_test(self):
        result = self.run_selected("tests/unit.test.cjs::passes (a.b)")
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(sorted(os.listdir(self.ran)), ["node-passes"])

    def test_a_failure_does_not_stop_the_commands_after_it(self):
        result = self.run_selected("tests/unit.test.cjs::fails", "tools/sample-test.py::test_passes")
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("test-selected: failed (exit 1): node --test", result.stderr)
        self.assertEqual(sorted(os.listdir(self.ran)), ["node-fails", "python-passes"])

    def test_user_daemon_settings_do_not_reach_the_tests(self):
        (self.root / "tools/env-test.py").write_text(textwrap.dedent("""\
            import os
            import unittest

            class Environment(unittest.TestCase):
                def test_settings_are_unset(self):
                    self.assertNotIn("TRELLIS_SEARCH_MODEL", os.environ)

            unittest.main()
        """))
        result = self.run_selected("tools/env-test.py", env={"TRELLIS_SEARCH_MODEL": "local"})
        self.assertEqual(result.returncode, 0, result.stderr)


class CargoStub(Checkout):
    """Cargo replaced by a recorder: how it is invoked, without building anything."""

    def stub(self, version):
        directory = self.outside / "bin"
        directory.mkdir()
        cargo = directory / "cargo"
        cargo.write_text(textwrap.dedent(f"""\
            #!/usr/bin/env python3
            import json, os, sys
            if sys.argv[1:] == ["nextest", "--version"]:
                print("cargo-nextest {version}")
                sys.exit(0)
            with open(os.path.join(os.environ["RAN"], "cargo"), "a") as log:
                log.write(json.dumps([sys.argv[1:], os.getcwd(), os.environ["CARGO_TARGET_DIR"]]) + "\\n")
            sys.exit(3 if "single" in sys.argv else 0)
        """))
        cargo.chmod(0o755)
        return {"PATH": f"{directory}{os.pathsep}{os.environ['PATH']}"}

    def test_each_selector_is_its_own_invocation_from_the_root(self):
        result = self.run_selected("src/alpha.rs", "tests/single.rs", "tests/suite/cases.rs::passes",
                                   env=self.stub("0.9.150"))
        self.assertEqual(result.returncode, 3, result.stdout + result.stderr)
        calls = [json.loads(line) for line in (self.ran / "cargo").read_text().splitlines()]
        flags = NEXTEST.split()[1:]
        target = f"{self.root}/target-test-support"
        self.assertEqual(calls, [
            [flags + ["--lib", "-E", "test(/^alpha::/)"], str(self.root), target],
            [flags + ["--test", "single"], str(self.root), target],
            [flags + ["--test", "suite", "-E", "test(/^cases::(.+::)?passes$/)"], str(self.root), target],
        ])

    def test_an_affected_nextest_runs_nothing(self):
        result = self.run_selected("tools/sample-test.py::test_passes", "tests/single.rs",
                                   env=self.stub("0.9.149"))
        self.assertEqual(result.returncode, 127)
        self.assertIn("GHSA-vc25-qg58-w57c", result.stderr)
        self.assertEqual(sorted(os.listdir(self.ran)), [])


def nextest_installed():
    try:
        return subprocess.run(["cargo", "nextest", "--version"], cwd=REPOSITORY,
                              capture_output=True).returncode == 0
    except OSError:
        return False


@unittest.skipUnless(nextest_installed(), "cargo-nextest is not installed")
class CargoRuns(Checkout):
    """The synthetic crate under the real pinned toolchain and nextest; it has no dependencies."""

    def setUp(self):
        super().setUp()
        shutil.copy(REPOSITORY / "rust-toolchain.toml", self.root / "rust-toolchain.toml")

    def test_selectors_run_their_own_tests_only(self):
        # The library and the suite binary each hold a failing test beside the selected ones.
        passing = ("src/alpha.rs", "src/gamma/mod.rs::passes", "tests/suite/cases.rs::passes",
                   "tests/suite/borrowed.rs", "tests/single.rs")
        result = self.run_selected(*passing)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(result.stdout.count("==> CARGO_TARGET_DIR="), len(passing))

    def test_a_selected_failure_fails_and_an_empty_selection_fails(self):
        result = self.run_selected("src/gamma/mod.rs")
        self.assertEqual(result.returncode, 100, result.stdout + result.stderr)
        result = self.run_selected("tests/suite/cases.rs::fails")
        self.assertEqual(result.returncode, 100, result.stdout + result.stderr)
        # nextest's own status for "no tests to run": a file with no tests does not pass.
        result = self.run_selected("src/gamma/delta.rs")
        self.assertEqual(result.returncode, 4, result.stdout + result.stderr)


