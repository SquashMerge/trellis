// Field-path tables retain the contract's declaration order (not lexical order).
export const enumTables = Object.freeze(
  (function collect() {
    const found = {};
    function visit(spec, path, seen = new Set()) {
      if (typeof spec === "string") {
        if (!Object.hasOwn(schemas, spec) || seen.has(spec)) return;
        return visit(schemas[spec], path, new Set([...seen, spec]));
      }
      if (spec.enum) {
        found[path] = Object.freeze([...spec.enum]);
        return;
      }
      if (spec.nullable) return visit(spec.nullable, path, seen);
      if (spec.array) return visit(spec.array, `${path}[]`, seen);
      if (spec.either)
        return spec.either.forEach((v, i) => visit(v, `${path}|${i}`, seen));
      if (spec.union)
        return Object.entries(spec.union.variants).forEach(([variant, v]) =>
          visit(v, `${path}:${variant}`, seen),
        );
      if (spec.object)
        Object.entries(spec.object).forEach(([key, v]) =>
          visit(v, `${path}.${key}`, seen),
        );
    }
    for (const [name, spec] of Object.entries(schemas))
      visit(spec, name, new Set([name]));
    return found;
  })(),
);
